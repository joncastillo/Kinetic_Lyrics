// Run with: node tests/scene_controls_dom.cjs <path to jsdom> <catalogue JSON>
// This is an isolated DOM unit test; it does not launch or control a browser.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {JSDOM}=require(path.resolve(process.argv[2]));
const html=fs.readFileSync('src/frontend/studio.html','utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,'');
const dom=new JSDOM(html,{runScripts:'outside-only',url:'http://localhost/'});
const w=dom.window;
w.renderProductionStages=()=>{};
const source=fs.readFileSync('src/frontend/studio-models.js','utf8');
const begin=source.indexOf('const KINETIC_DEFAULTS=');
const end=source.indexOf("document.addEventListener('DOMContentLoaded',()=>{\n document.querySelectorAll('[data-kinetic]");
w.eval(source.slice(begin,end));
w.eval(fs.readFileSync('src/frontend/studio-scenes.js','utf8'));
w.renderSceneEffects(JSON.parse(fs.readFileSync(process.argv[3],'utf8')),JSON.parse(fs.readFileSync(process.argv[4],'utf8')));
const q=s=>w.document.querySelector(s);
const selected=()=>[...w.document.querySelectorAll('[data-kinetic-list="scenes"]:checked')].map(x=>x.value);
assert.equal(w.document.querySelectorAll('.scene-choice').length,32);
assert.equal(w.document.querySelectorAll('.scene-config').length,32);
const before=selected();
const filter=q('#sceneFilters select');filter.value='minimalist';filter.dispatchEvent(new w.Event('change'));
assert.equal(w.document.querySelectorAll('.scene-choice[data-matches="true"]').length,5);
assert.deepEqual(selected(),before);
const search=q('#sceneFilters input');search.value='spotlight';search.dispatchEvent(new w.Event('input'));
assert.equal(w.document.querySelectorAll('.scene-choice[data-matches="true"]').length,1);
const color=q('[data-scene-id="editorial"][data-scene-setting="accent"]');
color.value='invalid';color.dispatchEvent(new w.Event('input'));assert.equal(color.checkValidity(),false);
assert.equal(w.sceneOverrides().editorial,undefined);
color.value='#aabbcc';color.dispatchEvent(new w.Event('input'));assert.equal(color.checkValidity(),true);
w.saveSceneOverride('word-wall','motion',0);w.storeKineticControls();w.syncKineticControls();
assert.equal(w.sceneOverrides().editorial.accent,'#aabbcc');
assert.equal(w.sceneOverrides()['word-wall'].motion,0);
const variant=q('[data-scene-id="word-seal"][data-scene-setting="shape"]');
variant.value='round';variant.dispatchEvent(new w.Event('change'));assert.equal(w.sceneOverrides()['word-seal'].shape,'round');
variant.value='auto';variant.dispatchEvent(new w.Event('change'));assert.equal(w.sceneOverrides()['word-seal'],undefined);
const url=new URL(q('.scene-thumbnail[data-scene="editorial"]').dataset.requestedSrc,'http://localhost');
assert.equal(JSON.parse(url.searchParams.get('settings')).accent,'#aabbcc');
w.saveSceneOverride('editorial',null);
assert.equal(w.sceneOverrides().editorial,undefined);assert.equal(w.sceneOverrides()['word-wall'].motion,0);
assert.equal(q('.scene-config[data-scene="editorial"] [data-scene-reset]').disabled,true);
q('#kinetic').value=JSON.stringify({scene_settings:{'quiet-focus':{size:1.2}},scenes:['quiet-focus']});
w.syncKineticControls();
assert.equal(q('[data-scene-id="quiet-focus"][data-scene-setting="size"]').value,'1.2');
assert.equal(JSON.parse(new URL(q('.scene-thumbnail[data-scene="quiet-focus"]').dataset.requestedSrc,'http://localhost').searchParams.get('settings')).size,1.2);
assert.deepEqual(selected(),['quiet-focus']);
const last=q('[data-kinetic-list="scenes"][value="quiet-focus"]');last.checked=false;last.dispatchEvent(new w.Event('input'));
assert.equal(last.checked,true);
assert.equal(w.sceneOverrides()['quiet-focus'].size,1.2);
const oldBackground=w.scenePreviewBackground('editorial');
w.changeSceneBackground('editorial',1);assert.notEqual(w.scenePreviewBackground('editorial'),oldBackground);
const activeSettings=q('#kinetic').value;w.changeSceneBackground('editorial',-1);assert.equal(q('#kinetic').value,activeSettings);
const slider=q('[data-scene-id="baseline-reveal"][data-scene-setting="size"]');slider.value='1.3';slider.dispatchEvent(new w.Event('input'));assert.equal(w.sceneOverrides()['baseline-reveal'].size,1.3);
const picker=q('[data-scene-color="editorial"] [type=color]');picker.value='#12ab34';picker.dispatchEvent(new w.Event('input'));assert.equal(w.sceneOverrides().editorial.accent,'#12ab34');
assert.equal(w.document.querySelectorAll('.scene-family').length,9);
console.log('PASS: catalogue, tag/search filters, selection guard, validation, select variants, persistence, preview refresh, isolated reset and session restoration');
dom.window.close();
